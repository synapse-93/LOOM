def test_pipeline_runner_preserves_checkpoints(tmp_path: Path) -> None:
    """Verify run_phase2_reconstruction_pipeline preserves checkpoints in disk hierarchy."""
    frame_dir = tmp_path / "frames"
    frame_dir.mkdir(parents=True, exist_ok=True)
    frame = frame_dir / "frame_0001.png"
    frame.write_bytes(b"dummy")

    mock_sparse = tmp_path / "mock_sparse" / "points3D.ply"
    mock_sparse.parent.mkdir(parents=True, exist_ok=True)
    mock_sparse.write_text("ply\nformat ascii 1.0\nelement vertex 3000\nend_header\n")

    mock_dense = tmp_path / "mock_dense" / "fused.ply"
    mock_dense.parent.mkdir(parents=True, exist_ok=True)
    mock_dense.write_text("ply\nformat ascii 1.0\nelement vertex 62000\nend_header\n")

    mock_mesh = tmp_path / "mock_mesh" / "meshed-poisson.ply"
    mock_mesh.parent.mkdir(parents=True, exist_ok=True)
    mock_mesh.write_text("ply\nformat ascii 1.0\nelement vertex 30000\nend_header\n")

    mock_result = ReconstructionResult(
        success=True,
        status=ReconstructionStatus.SUCCESS,
        backend_name="colmap",
        mesh_path=mock_mesh,
        dense_point_cloud_path=mock_dense,
        sparse_reconstruction_path=mock_sparse,
    )

    with patch("loom.reconstruction.runner.ReconstructionRunner.get_engine") as mock_engine_get:
        mock_engine = MagicMock()
        mock_engine.reconstruct.return_value = mock_result
        mock_engine_get.return_value = mock_engine

        result, checkpoints, report_path = run_phase2_reconstruction_pipeline(
            frames=[frame],
            output_dir=tmp_path / "outputs",
            run_id="run_shoe_test",
            dense=True,
        )

    assert result.success is True
    assert checkpoints.run_name == "run_shoe_test"
    assert checkpoints.point_count == 62000
    assert checkpoints.insufficient_coverage_warning is False

    # Verify standard disk paths
    assert (tmp_path / "outputs" / "reconstructions" / "run_shoe_test" / "01_sparse" / "points3D.ply").is_file()
    assert (tmp_path / "outputs" / "reconstructions" / "run_shoe_test" / "02_dense" / "fused.ply").is_file()
    assert (tmp_path / "outputs" / "reconstructions" / "run_shoe_test" / "03_raw_mesh" / "meshed-poisson.ply").is_file()
    assert report_path.is_file()

