def test_read_ply_vertex_count_ascii(tmp_path: Path) -> None:
    """Verify reading vertex count from ASCII PLY header."""
    ply_file = tmp_path / "test_ascii.ply"
    ply_content = (
        "ply\n"
        "format ascii 1.0\n"
        "comment generated by loom test\n"
        "element vertex 75432\n"
        "property float x\n"
        "property float y\n"
        "property float z\n"
        "end_header\n"
        "0.0 0.0 0.0\n"
    )
    ply_file.write_text(ply_content)

    count = read_ply_vertex_count(ply_file)
    assert count == 75432


def test_read_ply_vertex_count_binary(tmp_path: Path) -> None:
    """Verify reading vertex count from binary PLY header."""
    ply_file = tmp_path / "test_bin.ply"
    header = (
        b"ply\n"
        b"format binary_little_endian 1.0\n"
        b"element vertex 125000\n"
        b"property float x\n"
        b"property float y\n"
        b"property float z\n"
        b"end_header\n"
    )
    ply_file.write_bytes(header + b"\x00" * 24)

    count = read_ply_vertex_count(ply_file)
    assert count == 125000


def test_compute_ply_density(tmp_path: Path) -> None:
    """Verify compute_ply_density computes points / volume."""
    ply_file = tmp_path / "box_cloud.ply"
    # A box of 10 x 10 x 10 = 1000 volume, with 8 vertices
    ply_content = (
        "ply\n"
        "format ascii 1.0\n"
        "element vertex 8\n"
        "property float x\n"
        "property float y\n"
        "property float z\n"
        "end_header\n"
        "0.0 0.0 0.0\n"
        "10.0 0.0 0.0\n"
        "0.0 10.0 0.0\n"
        "10.0 10.0 0.0\n"
        "0.0 0.0 10.0\n"
        "10.0 0.0 10.0\n"
        "0.0 10.0 10.0\n"
        "10.0 10.0 10.0\n"
    )
    ply_file.write_text(ply_content)

    density = compute_ply_density(ply_file, point_count=8)
    # volume = 10 * 10 * 10 = 1000, density = 8 / 1000 = 0.008
    assert abs(density - 0.008) < 1e-4


