def test_reconstruction_checkpoints_export_disk_structure(tmp_path: Path) -> None:
    """Verify intermediate reconstruction files are exported to:
        outputs/reconstructions/<run_name>/
            01_sparse/points3D.ply
            02_dense/fused.ply
            03_raw_mesh/meshed-poisson.ply
    """
    output_root = tmp_path / "outputs"
    run_name = "test_run_shoe_001"

    # Create dummy source files
    sparse_src = tmp_path / "src_sparse" / "points3D.ply"
    sparse_src.parent.mkdir(parents=True, exist_ok=True)
    sparse_src.write_text("ply\nformat ascii 1.0\nelement vertex 2500\nend_header\n")

    dense_src = tmp_path / "src_dense" / "fused.ply"
    dense_src.parent.mkdir(parents=True, exist_ok=True)
    dense_src.write_text("ply\nformat ascii 1.0\nelement vertex 80000\nend_header\n")

    mesh_src = tmp_path / "src_mesh" / "meshed-poisson.ply"
    mesh_src.parent.mkdir(parents=True, exist_ok=True)
    mesh_src.write_text("ply\nformat ascii 1.0\nelement vertex 40000\nelement face 80000\nend_header\n")

    artifact = export_reconstruction_checkpoints(
        run_name=run_name,
        output_root=output_root,
        sparse_source=sparse_src,
        dense_source=dense_src,
        mesh_source=mesh_src,
        min_points_threshold=50000,
    )

    # 1. Verify Disk Structure
    expected_sparse = output_root / "reconstructions" / run_name / "01_sparse" / "points3D.ply"
    expected_dense = output_root / "reconstructions" / run_name / "02_dense" / "fused.ply"
    expected_mesh = output_root / "reconstructions" / run_name / "03_raw_mesh" / "meshed-poisson.ply"

    assert expected_sparse.is_file(), f"Missing {expected_sparse}"
    assert expected_dense.is_file(), f"Missing {expected_dense}"
    assert expected_mesh.is_file(), f"Missing {expected_mesh}"

    # 2. Verify Artifact Properties
    assert isinstance(artifact, ReconstructionCheckpointsArtifact)
    assert artifact.sparse_points_path == expected_sparse.resolve()
    assert artifact.dense_point_cloud_path == expected_dense.resolve()
    assert artifact.raw_mesh_path == expected_mesh.resolve()
    assert artifact.point_count == 80000
    assert artifact.insufficient_coverage_warning is False
    assert artifact.is_dense_sufficient is True


def test_point_cloud_diagnostic_low_points_warning(tmp_path: Path, caplog: pytest.LogCaptureFixture) -> None:
    """Verify that points < 50,000 logs high-severity warning that parallax/coverage was insufficient."""
    output_root = tmp_path / "outputs"
    run_name = "low_density_shoe_run"

    dense_src = tmp_path / "fused.ply"
    # Vertex count is 34,200 (< 50,000 threshold)
    dense_src.write_text("ply\nformat ascii 1.0\nelement vertex 34200\nend_header\n")

    with caplog.at_level("WARNING"):
        artifact = export_reconstruction_checkpoints(
            run_name=run_name,
            output_root=output_root,
            dense_source=dense_src,
            min_points_threshold=50000,
        )

    # Verify diagnostic flags
    assert artifact.point_count == 34200
    assert artifact.insufficient_coverage_warning is True
    assert artifact.is_dense_sufficient is False

    # Verify High Severity Warning in logs
    warning_logged = any(
        "HIGH SEVERITY WARNING" in record.message and "insufficient" in record.message
        for record in caplog.records
    )
    assert warning_logged, f"Expected high-severity warning in log records: {[r.message for r in caplog.records]}"


def test_point_cloud_diagnostic_sufficient_points(tmp_path: Path, caplog: pytest.LogCaptureFixture) -> None:
    """Verify that points >= 50,000 passes without high-severity warning."""
    output_root = tmp_path / "outputs"
