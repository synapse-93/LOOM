def test_sparse_points_bin_conversion(tmp_path: Path) -> None:
    """Verify COLMAP binary points3D.bin is converted to standard points3D.ply."""
    bin_file = tmp_path / "points3D.bin"
    dest_ply = tmp_path / "01_sparse" / "points3D.ply"

    # Create dummy points3D.bin with 2 points
    # Header: num_points (uint64)
    data = struct.pack("<Q", 2)
    # Point 1: id=1, xyz=(1.0, 2.0, 3.0), rgb=(255, 0, 0), error=0.5, track_len=1, track=(10, 20)
    data += struct.pack("<Q", 1) + struct.pack("<3d", 1.0, 2.0, 3.0) + struct.pack("<3B", 255, 0, 0)
    data += struct.pack("<d", 0.5) + struct.pack("<Q", 1) + struct.pack("<2I", 10, 20)
    # Point 2: id=2, xyz=(4.0, 5.0, 6.0), rgb=(0, 255, 0), error=0.2, track_len=0
    data += struct.pack("<Q", 2) + struct.pack("<3d", 4.0, 5.0, 6.0) + struct.pack("<3B", 0, 255, 0)
    data += struct.pack("<d", 0.2) + struct.pack("<Q", 0)
    bin_file.write_bytes(data)

    exported = export_sparse_points_ply(bin_file, dest_ply)
    assert exported is not None
    assert exported.is_file()

    count = read_ply_vertex_count(exported)
    assert count == 2


